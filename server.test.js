const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'amor-api-'));
process.env.DATA_DIR=directory;
const {server}=require('./server');
let base;
const ready=new Promise(r=>server.listen(0,'127.0.0.1',()=>{base=`http://127.0.0.1:${server.address().port}`;r();}));
after(()=>{server.close();fs.rmSync(directory,{recursive:true,force:true});});
test('carta pública, edición protegida y sesión del administrador',async()=>{
 await ready;
 let r=await fetch(base+'/api/letter');assert.equal(r.status,200);const d=await r.json();assert.ok(d.message);
 r=await fetch(base+'/api/letter',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify(d)});assert.equal(r.status,401);
 r=await fetch(base+'/api/login',{method:'POST',body:JSON.stringify({username:'adminamor',password:'incorrecta'})});assert.equal(r.status,401);
 r=await fetch(base+'/api/login',{method:'POST',body:JSON.stringify({username:'adminamor',password:'Rosa!Luna2026#Carta'})});assert.equal(r.status,200);const cookie=r.headers.get('set-cookie').split(';')[0];assert.match(r.headers.get('set-cookie'),/HttpOnly/);
 r=await fetch(base+'/api/session',{headers:{cookie}});assert.equal((await r.json()).authenticated,true);
 r=await fetch(base+'/api/letter',{method:'PUT',headers:{cookie},body:JSON.stringify({...d,size:100})});assert.equal(r.status,400);
 const edited={...d,message:'Una carta con tildes y corazones. ♡\n'+ '💗'.repeat(7900),sender:'Firma persistente'};
 r=await fetch(base+'/api/letter',{method:'PUT',headers:{cookie},body:JSON.stringify({...d,sender:'Firma persistente'})});assert.equal(r.status,200);
 r=await fetch(base+'/api/letter');assert.equal((await r.json()).sender,'Firma persistente');
 assert.equal(JSON.parse(fs.readFileSync(path.join(directory,'letter.json'),'utf8')).sender,'Firma persistente');
 r=await fetch(base+'/api/letter',{method:'PUT',headers:{cookie},body:JSON.stringify({...d,message:'💗'.repeat(4000)})});assert.equal(r.status,200);
 r=await fetch(base+'/api/letter');assert.equal((await r.json()).message,'💗'.repeat(4000));
 r=await fetch(base+'/api/letter',{method:'PUT',headers:{cookie,origin:'https://otro.example'},body:JSON.stringify(d)});assert.equal(r.status,403);
 r=await fetch(base+'/api/letter',{method:'PUT',headers:{cookie},body:JSON.stringify(edited)});assert.equal(r.status,400);
 r=await fetch(base+'/api/logout',{method:'POST',headers:{cookie}});assert.equal(r.status,200);
 r=await fetch(base+'/api/session',{headers:{cookie}});assert.equal((await r.json()).authenticated,false);
 r=await fetch(base+'/server.js');assert.equal(r.status,404);
});
